"""Build the submission-history table for the core report (Section 3).

    .venv\\Scripts\\python.exe scripts\\submission_history.py              # uploaded submissions only
    .venv\\Scripts\\python.exe scripts\\submission_history.py --all        # also created-but-not-uploaded rows
    .venv\\Scripts\\python.exe scripts\\submission_history.py --data synthetic

Reads registry/submissions.csv, joins registry/experiments.csv on run_id (model,
selector, CV scheme) and writes reports/tables/core_submission_history.csv (every
column) and .md (report columns) to ssc.paths.tables_dir(--data). Read-only for
the registries; nothing else is changed.

Columns of the .md: sub_id, Kaggle (UTC) day, run_id, model, what the submission
asked, CV mean +/- std across repeats, the pre-registered expected public score,
the public score and the two "surprises" (public - expected, public - CV), and
whether it was selected as final. The private score is in the .csv only: it is
published after the deadline, when the report is already submitted.
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

import _common as C
from ssc import paths
from ssc.tracking import now_iso, read_registry

MD_COLS = ["sub_id", "day_utc", "run_id", "model", "description", "cv", "expected_public", "public_lb",
           "public_minus_expected", "public_minus_cv", "final"]


def build(source: str, include_all: bool) -> pd.DataFrame:
    subs = read_registry(paths.submissions_csv(source))
    if subs.empty:
        return subs
    exps = read_registry(paths.experiments_csv(source))
    if not exps.empty:
        keep = ["run_id", "data_source", "model", "selector", "cv", "cv_seed", "status"]
        subs = subs.merge(exps[keep].drop_duplicates("run_id"), on="run_id", how="left", suffixes=("", "_run"))
        # $SSC_ARCHIVE_ROOT may hold both sources in one registry: keep this source (and unknown runs)
        subs = subs[subs["data_source"].fillna(source).isin([source, ""])]
    else:
        subs = subs.assign(model="", selector="", cv="", cv_seed="")
    if not include_all:
        subs = subs[subs["submitted_at_utc"].fillna("") != ""]
    out = pd.DataFrame({
        "sub_id": subs["sub_id"],
        "day_utc": subs["submitted_at_utc"].fillna("").str[:10],
        "submitted_at_utc": subs["submitted_at_utc"].fillna(""),
        "run_id": subs["run_id"],
        "model": [m if s in ("", "none", None) or pd.isna(s) else f"{s}+{m}"
                  for s, m in zip(subs["selector"], subs["model"].fillna(""))],
        "description": subs["description"],
        "cv_scheme": [f"{c} seed {s}" if c else "" for c, s in zip(subs["cv"].fillna(""), subs["cv_seed"].fillna(""))],
        "cv_auc_mean": subs["cv_auc_mean"].map(C.to_float),
        "cv_auc_std_repeat": subs["cv_auc_std_repeat"].map(C.to_float),
        "expected_public": subs["expected_public"].map(C.to_float),
        "public_lb": subs["public_lb"].map(C.to_float),
        "private_lb": subs["private_lb"].map(C.to_float),
        "final": subs["selected_final"].fillna(""),
        "author": subs["author"],
        "notes": subs["notes"],
    })
    out["cv"] = [f"{C.fnum(m)} +/- {C.fnum(s)}" if m is not None else "" for m, s in
                 zip(out["cv_auc_mean"], out["cv_auc_std_repeat"])]
    out["public_minus_expected"] = out["public_lb"] - out["expected_public"]
    out["public_minus_cv"] = out["public_lb"] - out["cv_auc_mean"]
    return out.reset_index(drop=True)


def main() -> int:
    C.setup_console()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    C.add_data_arg(ap)
    ap.add_argument("--all", action="store_true", help="also list submissions that were created but not uploaded")
    args = ap.parse_args()
    source = paths.resolve_source(args.data)
    C.print_archive(source)

    table = build(source, args.all)
    if table.empty:
        print(f"no {'submissions' if args.all else 'uploaded submissions'} in {paths.submissions_csv(source)}; "
              "nothing written")
        return 0
    tdir = paths.tables_dir(source)
    tdir.mkdir(parents=True, exist_ok=True)
    csv_p, md_p = tdir / "core_submission_history.csv", tdir / "core_submission_history.md"
    table.to_csv(csv_p, index=False)
    md = table[MD_COLS].copy()
    for c in ("expected_public", "public_lb"):
        md[c] = md[c].map(C.fnum)
    for c in ("public_minus_expected", "public_minus_cv"):
        md[c] = md[c].map(lambda v: C.fnum(v, signed=True))
    with open(md_p, "w", encoding="utf-8") as f:
        f.write(f"<!-- generated by scripts/submission_history.py from {paths.submissions_csv(source).name} "
                f"at {now_iso()}; do not edit by hand -->\n")
        f.write(md.to_markdown(index=False, disable_numparse=True) + "\n")

    from tabulate import tabulate
    view = md.assign(description=md["description"].map(lambda s: s if len(s) <= 40 else s[:37] + "..."))
    print(tabulate(view.drop(columns=["run_id"]).to_numpy().tolist(),
                   headers=[c for c in MD_COLS if c != "run_id"], tablefmt="simple", disable_numparse=True))
    n_pub = int(table["public_lb"].notna().sum())
    print(f"\n{len(table)} submission(s), {n_pub} with a public score; written {C.rel(csv_p)} and {C.rel(md_p)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
